// Helper to look up product by ID or Slug
function getSarvamProductByIdOrSlug(param) {
  if (!param) return SARVAM_PRODUCTS[0]; // Default to Amrit Rasayana Gold
  const numericId = parseInt(param, 10);
  if (!isNaN(numericId)) {
    const found = SARVAM_PRODUCTS.find(p => p.id === numericId);
    if (found) return found;
  }
  const cleanSlug = String(param).trim().toLowerCase();
  const foundBySlug = SARVAM_PRODUCTS.find(p => p.slug === cleanSlug);
  return foundBySlug || SARVAM_PRODUCTS[0];
}
